#!/usr/bin/env python3
"""Build the shipped Fusion Pixel subset + its glyph-advance table.

Usage (needs `pip install fonttools`; run with `python3 -I`):

    python3 -I scripts/fonts/build-fusion-pixel.py <release-dir> <repo-root>

`<release-dir>` is the extracted official release
`fusion-pixel-font-12px-proportional-ttf-v<version>.zip` (the one
`fusion-pixel-12px-proportional-latin.ttf` ships in). Nothing from it is
executed; the script only reads the TTF and the licence texts.

Writes:
  packages/engine/assets/fonts/fusion-pixel/fusion-pixel-12px-proportional-latin-subset.ttf
  packages/engine/assets/fonts/fusion-pixel/OFL.txt, OFL-ark-pixel.txt
  packages/engine/src/services/fusion-pixel-12-metrics.ts   (advances, in UI pixels)

Fails when a character of the German catalogue or of a game's text has no
glyph in the font, apart from the editor-chrome symbols in CHROME_ONLY (the
editor draws those with the GTK system font, never with this one).
"""

import glob
import json
import re
import shutil
import sys
from collections import defaultdict
from pathlib import Path

from fontTools import subset
from fontTools.ttLib import TTFont

SOURCE = "fusion-pixel-12px-proportional-latin.ttf"
OUT_NAME = "fusion-pixel-12px-proportional-latin-subset.ttf"
SIZE_PX = 12

# Latin-1 + Latin Extended-A, typographic quotes, ellipsis, dashes, arrows.
BASE_RANGES = [(0x20, 0x7E), (0xA0, 0x17F)]
BASE_EXTRA = [
    0x2013, 0x2014, 0x2018, 0x2019, 0x201A, 0x201C, 0x201D, 0x201E, 0x2022,
    0x2026, 0x2039, 0x203A, 0x20AC, 0x2190, 0x2191, 0x2192, 0x2193, 0x2194,
    0x2212,
]  # fmt: skip
# Drawn by GTK's own font in the editor, never by the game font.
CHROME_ONLY = {0x22EF, 0x2713, 0x203A}


def catalogue_chars(root: Path) -> set[int]:
    chars: set[int] = set()
    po = (root / "packages/translations/de.po").read_text(encoding="utf8")
    for m in re.finditer(r'^(?:msg\w+(?:\[\d\])?\s+)?(".*")$', po, re.M):
        chars |= {ord(c) for c in json.loads(m.group(1))}

    def walk(o):
        if isinstance(o, str):
            yield o
        elif isinstance(o, dict):
            for v in o.values():
                yield from walk(v)
        elif isinstance(o, list):
            for v in o:
                yield from walk(v)

    for f in glob.glob(str(root / "games/**/*.json"), recursive=True):
        try:
            data = json.loads(Path(f).read_text(encoding="utf8"))
        except ValueError:
            continue
        for s in walk(data):
            chars |= {ord(c) for c in s}
    return {c for c in chars if c >= 0x20 and c != 0x7F}


def main() -> None:
    release, root = Path(sys.argv[1]), Path(sys.argv[2])
    src = release / SOURCE
    out_dir = root / "packages/engine/assets/fonts/fusion-pixel"
    out_dir.mkdir(parents=True, exist_ok=True)

    wanted = {c for lo, hi in BASE_RANGES for c in range(lo, hi + 1)} | set(BASE_EXTRA)
    needed = catalogue_chars(root)
    font = TTFont(src)
    cmap = font.getBestCmap()
    missing = sorted(c for c in needed if c not in cmap and c not in CHROME_ONLY and c != 0xAD)
    if missing:
        sys.exit("no glyph for: " + " ".join(f"U+{c:04X} {chr(c)}" for c in missing))
    keep = {c for c in wanted | needed if c in cmap}

    opts = subset.Options()
    opts.layout_features = ["kern", "ccmp", "locl"]
    opts.notdef_outline = True
    opts.hinting = False
    opts.name_IDs = [0, 1, 2, 3, 4, 5, 6, 8, 9, 11, 13, 14]
    sub = subset.load_font(str(src), opts)
    subsetter = subset.Subsetter(opts)
    subsetter.populate(unicodes=keep)
    subsetter.subset(sub)
    subset.save_font(sub, str(out_dir / OUT_NAME), opts)

    shutil.copyfile(release / "OFL.txt", out_dir / "OFL.txt")
    shutil.copyfile(release / "LICENSES/ark-pixel/OFL.txt", out_dir / "OFL-ark-pixel.txt")

    upem = font["head"].unitsPerEm
    scale = SIZE_PX / upem
    by_advance: dict[float, list[str]] = defaultdict(list)
    for cp in sorted(keep):
        adv = round(font["hmtx"][cmap[cp]][0] * scale, 2)
        by_advance[int(adv) if adv == int(adv) else adv].append(chr(cp))
    notdef = round(font["hmtx"][".notdef"][0] * scale, 2)

    rows = "\n".join(
        f"    {json.dumps(str(a))}: {json.dumps(''.join(chars), ensure_ascii=False)},"
        for a, chars in sorted(by_advance.items())
    )
    version = font["name"].getDebugName(5)
    (root / "packages/engine/src/services/fusion-pixel-12-metrics.ts").write_text(
        f"""// Generated by scripts/fonts/build-fusion-pixel.py from Fusion Pixel Font {version} — do not edit by hand.
import type {{ FontMetricsData }} from './font-metrics'

export const FUSION_PIXEL_12_METRICS: FontMetricsData = {{
  id: 'fusion-pixel-12',
  size: {SIZE_PX},
  fallbackAdvance: {int(notdef) if notdef == int(notdef) else notdef},
  advances: {{
{rows}
  }},
}}
""",
        encoding="utf8",
    )
    print("glyphs:", len(keep), "subset bytes:", (out_dir / OUT_NAME).stat().st_size)


if __name__ == "__main__":
    main()
