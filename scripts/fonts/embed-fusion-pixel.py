"""Embed the shipped Fusion Pixel subset as base64 in the engine.

The engine registers its built-in font through `FontFace` from bytes, so the
same code runs under GJS and in a browser and no host has to find a file.
Run after `build-fusion-pixel.py`:  python3 -I scripts/fonts/embed-fusion-pixel.py
"""
import base64
from pathlib import Path

root = Path(__file__).resolve().parents[2]
ttf = root / "packages/engine/assets/fonts/fusion-pixel/fusion-pixel-12px-proportional-latin-subset.ttf"
out = root / "packages/engine/src/services/pixel-font-data.ts"
data = base64.b64encode(ttf.read_bytes()).decode("ascii")
out.write_text(
    "// Generated by scripts/fonts/embed-fusion-pixel.py from the TTF in assets/fonts/fusion-pixel — do not edit by hand.\n"
    f"export const PIXEL_FONT_BASE64 =\n  '{data}'\n",
    encoding="utf8",
)
print("embedded", ttf.stat().st_size, "bytes")
