#!/usr/bin/env node
/**
 * Orphan-component guard.
 *
 * The ECS split says components are data and systems are logic. The
 * failure mode that split invites is a component that is BUILT and
 * attached on every spawn and READ by nothing: the editor offers the
 * feature, the data round-trips through save/load, the entity carries
 * it at runtime — and it does nothing. Every layer looks right except
 * the one that would make it work, so nobody notices.
 *
 * `CollisionComponent` is the worked example. `collisionSpec` labels it
 * *"Blocks movement"* in the component inspector, three entity templates
 * (chest / sign / door) seed it, `spawn-placement.spec.ts` asserts the
 * spawned entity has it — and no system anywhere queries it. The player
 * walks straight through every chest in the shipped templates.
 *
 * This guard fails (exit 1) if a `*.component.ts` class under
 * `packages/engine/src/components/` is referenced by no file outside its
 * own declaration, the components barrel, `packages/engine/src/entity/**`
 * (the specs that BUILD components) and `*.spec.ts`. In other words:
 * something constructs it, something tests it, nothing consumes it.
 *
 * An exception needs BOTH an `orphan-component-ok:` marker in the
 * component's own file (stating why, next to the code) and an entry in
 * `EXPECTED_EXEMPTIONS` below. The marker alone is not enough: pinning
 * the exempt components here means a new exemption cannot appear without
 * editing this script, so a deliberate gap stays distinguishable from a
 * comment someone added to silence the guard.
 *
 * Deliberate scope decisions:
 *  - Everything under `packages/engine/src/entity/**` counts as a
 *    BUILDER, not a reader — that subtree is the component-spec registry
 *    plus the spawn pipeline, i.e. the construction side by definition.
 *    A genuine reader placed there would be misclassified and the guard
 *    would under-report. Under-reporting is the safe direction: this
 *    guard must never accuse a live component.
 *  - A component read by another COMPONENT counts as read.
 *    `event-actions.component.ts` consumes `DialogueComponent` and
 *    `ScriptRefComponent`; a component-to-component read is a real read,
 *    so neither is reported.
 *  - `components/index.ts` is excluded. It is generated by `gjsify
 *    barrels` and re-exports with `export *` today, so it names no class
 *    — but if the generator ever emitted named re-exports it would turn
 *    every component into its own reader and silently disarm this guard.
 *  - Matching is by class NAME (a word-boundary match on the whole
 *    file), not by resolved TS symbol. Component class names in this
 *    repo are unique, unambiguous and never shadowed, so the cheap
 *    matcher is exact here and needs no `typescript` dependency in CI.
 *
 * Runs in CI (Node is already provisioned for the gjsify CLI bootstrap)
 * and locally via `gjsify run check:orphan-components` at the workspace
 * root.
 */
import { readdirSync, readFileSync } from 'node:fs'
import { dirname, join, relative } from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..')

/** Where component classes are declared, and the barrel that re-exports them. */
const COMPONENTS_DIR = 'packages/engine/src/components/'
const COMPONENTS_BARREL = `${COMPONENTS_DIR}index.ts`

/** The construction side: component specs + the spawn pipeline. */
const BUILDER_DIR = 'packages/engine/src/entity/'

/** Marker that lets a component declare itself deliberately unread. */
const ALLOW_MARKER = 'orphan-component-ok'

/**
 * Components allowed to have no reader, and why. Each must ALSO carry
 * the `orphan-component-ok:` marker in its own file. Every entry here is
 * a known gap or a deliberate escape hatch — none is "we will get to it
 * eventually"; see TODO.md for the ones with planned consumers.
 */
const EXPECTED_EXEMPTIONS = {
  CollisionComponent:
    'known gap: `collisionSpec` ships the user-visible "Blocks movement" label and three templates seed it, ' +
    'but the movement blocker system is unbuilt — the flag has no runtime effect yet (TODO.md, Engine / runtime)',
  SpriteRefComponent:
    'known gap: the placement graphic is built from the DEFINITION (`buildPlacementGraphic(def, …)`), so the ' +
    'attached component is inert until a runtime graphic system reads it (TODO.md, Engine / runtime)',
  NpcRouteComponent:
    'known gap: waypoints + facing are authored and persisted; `NpcMovementSystem` is unbuilt (TODO.md, Engine / runtime)',
  CustomDataComponent:
    'by design: the project-script escape hatch. The ENGINE must never read `bag` — a reader here would be the bug',
}

/**
 * Lower bound on the component classes a healthy scan finds. A walk that
 * silently returned nothing would report "0 violations" and look
 * identical to a clean tree.
 */
const MIN_COMPONENT_CLASSES = 20

/** Expand the root `package.json#workspaces` globs (one level of `dir/*` only — matches this repo). */
function listWorkspacePackageDirs(root) {
  const rootPkg = JSON.parse(readFileSync(join(root, 'package.json'), 'utf8'))
  const dirs = []
  for (const pattern of rootPkg.workspaces ?? []) {
    const m = pattern.match(/^(.*)\/\*$/)
    if (!m) {
      dirs.push(pattern)
      continue
    }
    const base = join(root, m[1])
    for (const entry of readdirSync(base, { withFileTypes: true })) {
      if (entry.isDirectory()) dirs.push(join(m[1], entry.name))
    }
  }
  return dirs
}

/** Recursively collect `*.ts`/`*.mts` files under `dir` (skips node_modules/dist). */
function collectSourceFiles(dir, acc = []) {
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    if (entry.name === 'node_modules' || entry.name === 'dist') continue
    const full = join(dir, entry.name)
    if (entry.isDirectory()) collectSourceFiles(full, acc)
    else if (entry.name.endsWith('.ts') || entry.name.endsWith('.mts')) acc.push(full)
  }
  return acc
}

/** @type {{path: string, source: string}[]} every workspace source file, read once */
const sources = []
for (const dir of listWorkspacePackageDirs(ROOT)) {
  let files
  try {
    files = collectSourceFiles(join(ROOT, dir, 'src'))
  } catch {
    continue // no src/ directory (e.g. games/* data-only packages)
  }
  for (const file of files) {
    sources.push({ path: relative(ROOT, file).split('\\').join('/'), source: readFileSync(file, 'utf8') })
  }
}

/** @type {Map<string, string>} component class name → declaring file */
const componentClasses = new Map()
for (const { path, source } of sources) {
  if (!path.startsWith(COMPONENTS_DIR) || !path.endsWith('.component.ts')) continue
  for (const m of source.matchAll(/export class (\w+) extends \w*Component\b/g)) componentClasses.set(m[1], path)
}

const orphans = []
for (const [name, declaredIn] of [...componentClasses].sort(([a], [b]) => a.localeCompare(b))) {
  const reference = new RegExp(`\\b${name}\\b`)
  const readers = sources.filter(({ path, source }) => {
    if (path === declaredIn || path === COMPONENTS_BARREL) return false
    if (path.endsWith('.spec.ts') || path.startsWith(BUILDER_DIR)) return false
    return reference.test(source)
  })
  if (readers.length === 0) orphans.push({ name, declaredIn })
}

let failures = 0

if (componentClasses.size < MIN_COMPONENT_CLASSES) {
  console.error(
    `✗ found only ${componentClasses.size} component class(es) under ${COMPONENTS_DIR} — the walk is broken, not the tree`,
  )
  failures++
}

/** Components whose marker actually suppressed a would-be violation. */
const suppressed = new Set()

for (const { name, declaredIn } of orphans) {
  const marked = readFileSync(join(ROOT, declaredIn), 'utf8').includes(ALLOW_MARKER)
  const pinned = Object.hasOwn(EXPECTED_EXEMPTIONS, name)
  if (marked && pinned) {
    suppressed.add(name)
    continue
  }
  if (marked && !pinned) {
    console.error(`✗ ${declaredIn} marks ${name} "${ALLOW_MARKER}" but ${name} is not listed in EXPECTED_EXEMPTIONS`)
    failures++
    continue
  }
  if (!marked && pinned) {
    console.error(`✗ ${name} is listed in EXPECTED_EXEMPTIONS but ${declaredIn} carries no "${ALLOW_MARKER}" marker`)
    failures++
    continue
  }
  console.error(
    `✗ ${declaredIn} declares ${name}, which is built by a component spec but read by no system — ` +
      'the feature it represents has no runtime effect',
  )
  failures++
}

// A stale entry is one naming a component that is no longer an orphan at
// all — not one whose marker is merely missing, which is reported above.
const orphanNames = new Set(orphans.map((o) => o.name))
for (const name of Object.keys(EXPECTED_EXEMPTIONS).sort()) {
  if (orphanNames.has(name)) continue
  console.error(`✗ ${name} is listed in EXPECTED_EXEMPTIONS but now has a reader — drop the entry and the marker`)
  failures++
}

if (failures > 0) {
  console.error(
    `\n${failures} orphan-component violation(s). Give the component a system that reads it, delete it, or — ` +
      `if the consumer is genuinely planned work — add the "${ALLOW_MARKER}:" marker to its file, an entry to ` +
      'EXPECTED_EXEMPTIONS in this script, and a line to TODO.md.',
  )
  process.exit(1)
}
console.log(
  `✓ ${componentClasses.size - suppressed.size} of ${componentClasses.size} engine components are read by a system ` +
    `(${suppressed.size} annotated as known gaps: ${[...suppressed].sort().join(', ')})`,
)
